#!/usr/bin/env python3
"""Merge recorded NVN shader/pipeline rows into a bundled pso_manifest.tsv.

The runtime files are deliberately append-only and device-local.  This helper
promotes their portable S/R/C rows into a profile manifest while preserving
first-use order, dropping duplicates, and replacing the destination
atomically.
"""

import argparse
import os
import tempfile
from pathlib import Path


HEADER = (
    "# Prewarm seed list (shipped in the app, next to shader_map.tsv). "
    "Rows: S<TAB>shader key<TAB>stage / R<TAB>render pipeline key "
    "(pso_skey hex) / C<TAB>compute shader key.\n"
    "# Generated by scripts/merge_pso_manifest.py from recorded Mac/device "
    "runs; row order is first-use order.\n"
)


def rows(path: Path):
    """Yield valid portable manifest rows, rejecting malformed input early."""
    if not path.is_file():
        raise SystemExit(f"error: file not found: {path}")
    for number, raw in enumerate(path.read_text(errors="replace").splitlines(), 1):
        line = raw.strip("\r")
        if not line or line.startswith("#"):
            continue
        fields = line.split("\t")
        if fields[0] not in {"S", "R", "C"}:
            raise SystemExit(f"error: {path}:{number}: unknown row kind {fields[0]!r}")
        expected = 3 if fields[0] == "S" else 2
        if len(fields) != expected or any(not field for field in fields[1:]):
            raise SystemExit(f"error: {path}:{number}: malformed {fields[0]} row")
        yield line


def destination_header(path: Path) -> str:
    if not path.is_file():
        return HEADER
    comments = [line for line in path.read_text(errors="replace").splitlines(True) if line.startswith("#")]
    if any("Provisional profile: empty" in line for line in comments):
        comments = [line for line in comments if "Provisional profile: empty" not in line]
        comments.insert(1, "# Generated by scripts/merge_pso_manifest.py from recorded Mac/device runs; row order is first-use order.\n")
    return "".join(comments) or HEADER


def main():
    ap = argparse.ArgumentParser(description="Merge recorded S/R/C rows into a pso_manifest.tsv.")
    ap.add_argument("manifest", type=Path, help="destination profile pso_manifest.tsv")
    ap.add_argument("recorded", nargs="+", type=Path, help="DM_PSO_RECORD or pso_user.tsv files, in first-use order")
    args = ap.parse_args()

    seen = set()
    ordered = []
    if args.manifest.is_file():
        for line in rows(args.manifest):
            if line not in seen:
                seen.add(line)
                ordered.append(line)
    for path in args.recorded:
        for line in rows(path):
            if line not in seen:
                seen.add(line)
                ordered.append(line)

    args.manifest.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp_name = tempfile.mkstemp(prefix=f".{args.manifest.name}.", dir=args.manifest.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as out:
            out.write(destination_header(args.manifest))
            out.writelines(f"{line}\n" for line in ordered)
            out.flush()
            os.fsync(out.fileno())
        os.replace(tmp_name, args.manifest)
    except BaseException:
        try:
            os.unlink(tmp_name)
        except FileNotFoundError:
            pass
        raise
    print(f"{args.manifest}: {len(ordered)} unique prewarm rows")


if __name__ == "__main__":
    main()
